"""Build the ObsCore JSON manifest for SKAVA's ingestion API.

A manifest is a list of dicts; each dict carries all ObsCore fields the
extractor was able to recover, plus the publisher-injected fields:

* ``node_id``        — the Node.code from config (e.g. ``POWER9``)
* ``access_url``     — derived from ``file_serve_url_pattern``
* ``access_estsize`` — file size in KB
* ``is_public``      — from config defaults
* ``obs_collection`` — from config defaults if extractor didn't set it
* ``license``        — from config defaults
* ``provenance_json``— dict with ``publisher_label``, ``sha256``, ``rel_path``

A record without ``obs_id`` is auto-generated by hashing the relative
path — deterministic, unique per node, stable across re-runs. Operators
can override by setting an explicit ``obs_id`` rule in a future
config field.
"""
from __future__ import annotations

import hashlib
import json
import logging
from pathlib import Path
from typing import Any

from skava_publisher.config import PublisherConfig

logger = logging.getLogger("skava.publisher.manifest")


def derive_obs_id(node_code: str, rel_path: Path) -> str:
    """Stable obs_id from (node_code, relative path). Survives re-runs."""
    h = hashlib.sha256(f"{node_code}::{rel_path.as_posix()}".encode("utf-8")).hexdigest()
    return f"{node_code.lower()}-{h[:16]}"


def build_record(
    *,
    cfg: PublisherConfig,
    abs_path: Path,
    rel_path: Path,
    size_bytes: int,
    sha256: str | None,
    extracted: dict[str, Any],
) -> dict[str, Any]:
    record: dict[str, Any] = dict(extracted)

    # Identifier — extractor's value wins, otherwise derive deterministically.
    if not record.get("obs_id"):
        record["obs_id"] = derive_obs_id(cfg.node.code, rel_path)

    # Node + access URL — always overwrite, even if the extractor set
    # one (the extractor doesn't know our serving config).
    record["node_id"] = cfg.node.code
    record["access_url"] = cfg.node.file_serve_url_pattern.format(
        relpath=rel_path.as_posix()
    )

    # Size estimate in KB (ObsCore convention).
    if "access_estsize" not in record:
        record["access_estsize"] = max(1, size_bytes // 1024)

    # Defaults overlay.
    if cfg.defaults.obs_collection and not record.get("obs_collection"):
        record["obs_collection"] = cfg.defaults.obs_collection
    if cfg.defaults.license and not record.get("license"):
        record["license"] = cfg.defaults.license
    record.setdefault("is_public", cfg.defaults.is_public)

    # Provenance.
    prov: dict[str, Any] = dict(record.get("provenance_json") or {})
    prov.setdefault("rel_path", rel_path.as_posix())
    if sha256:
        prov.setdefault("sha256", sha256)
    if cfg.defaults.publisher_label:
        prov.setdefault("publisher_label", cfg.defaults.publisher_label)
    record["provenance_json"] = prov

    return record


def dump_manifest(records: list[dict[str, Any]], path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(
        json.dumps({"records": records}, indent=2, default=str, ensure_ascii=False),
        encoding="utf-8",
    )
